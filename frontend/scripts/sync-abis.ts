#!/usr/bin/env tsx
/**
 * Extract contract ABIs and the latest `deployments/*.json` from the Foundry
 * build so the frontend can import them as typed `const` arrays.
 *
 * Writes:
 *   src/abi/<Contract>.ts   — one `const` ABI per contract (viem-compatible)
 *   src/deployments/<chainId>.json — merged copies of the Forge output
 *
 * Invoked by `pnpm sync-abis`. Run `forge build` first.
 */
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const here = path.dirname(url.fileURLToPath(import.meta.url));
const frontend = path.resolve(here, "..");
const contracts = path.resolve(frontend, "../contracts");
const outDir = path.join(contracts, "out");
const abiDir = path.join(frontend, "src/abi");
const depsSrc = path.join(contracts, "deployments");
const depsDst = path.join(frontend, "src/deployments");
// The SDK (../sdk) ships the same ABIs and addresses, so it is kept in step here.
const sdkSrc = path.resolve(frontend, "../sdk/src");
const abiDirs = [abiDir, ...(fs.existsSync(sdkSrc) ? [path.join(sdkSrc, "abi")] : [])];
const depsDsts = [depsDst, ...(fs.existsSync(sdkSrc) ? [path.join(sdkSrc, "deployments")] : [])];

const WANTED = [
  "WPOT",
  "MockStable",
  "InsuranceFund",
  "StabilizationReserve",
  "StakingVault",
  "SwapDesk",
  "PolicyNFT",
  "MandateManager",
  "OracleCommittee",
  "X402Dollar",
  "XusdGateway",
  "TokenBridge",
];

function readForgeArtifact(name: string): unknown[] | null {
  // Forge drops artifacts at out/<Source>.sol/<Contract>.json. The source file
  // name usually matches the contract name but not always (e.g. WpotBuckets
  // defines InsuranceFund and StabilizationReserve). Walk `out/` to find it.
  const stack = [outDir];
  while (stack.length) {
    const dir = stack.pop()!;
    if (!fs.existsSync(dir)) continue;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        stack.push(full);
        continue;
      }
      if (entry.name === `${name}.json`) {
        const json = JSON.parse(fs.readFileSync(full, "utf8"));
        if (Array.isArray(json.abi)) return json.abi;
      }
    }
  }
  return null;
}

function writeAbi(name: string, abi: unknown[]) {
  const body = `// Auto-generated by scripts/sync-abis.ts — do not edit by hand.
export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;
`;
  for (const dir of abiDirs) {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, `${name}.ts`), body);
  }
}

function syncDeployments() {
  if (!fs.existsSync(depsSrc)) {
    console.log("sync-abis: no contracts/deployments/, skipping address sync");
    return;
  }
  for (const dst of depsDsts) {
    fs.mkdirSync(dst, { recursive: true });
    for (const file of fs.readdirSync(depsSrc)) {
      if (!file.endsWith(".json")) continue;
      fs.copyFileSync(path.join(depsSrc, file), path.join(dst, file));
    }
  }
  console.log(`sync-abis: copied deployments/ to ${depsDsts.length} place(s)`);
}

let found = 0;
for (const name of WANTED) {
  const abi = readForgeArtifact(name);
  if (!abi) {
    console.warn(`sync-abis: ${name} not found under contracts/out/ (did you run forge build?)`);
    continue;
  }
  writeAbi(name, abi);
  console.log(`sync-abis: wrote src/abi/${name}.ts (${abi.length} entries)`);
  found += 1;
}
syncDeployments();

if (found === 0) {
  console.error("sync-abis: no artifacts found — run `cd ../contracts && forge build`");
  process.exit(1);
}
